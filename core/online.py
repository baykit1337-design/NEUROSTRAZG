"""Есть ли связь у нас самих — прежде чем винить сайт.

Отличить «сайт лёг» от «у меня отвалился интернет» по тексту ошибки
нельзя: curl в обоих случаях говорит одно и то же — не дозвонились. А
делать в этих двух случаях надо противоположное. Сайт лёг — прогон
останавливают и человеку сообщают. Пропала связь — прогон надо
подождать: книга на середине, и заканчивать её на середине незачем,
связь вернётся через минуту.

Спрашиваем голые адреса, а не имена. Причина не в скорости: имена может
не отдавать сам DNS, и это третья, отдельная беда со своим лечением —
другой DNS или посредник, и в программе для этого есть своя ручка. Пойди
проверка через имя, «DNS молчит» выглядело бы как «интернета нет», и
человека послали бы чинить кабель, который цел.

Адресов несколько и они разных хозяев: один может быть закрыт у
провайдера, и по одному молчащему адресу объявлять, что интернета нет,
нельзя. «Связи нет» — это когда не ответил ни один.
"""

from __future__ import annotations

import logging
import socket

log = logging.getLogger(__name__)

#: Кого спрашиваем. Публичные DNS-резолверы: они держат 443-й порт,
#: отвечают отовсюду и не принадлежат одной компании — если молчат все
#: три, дело точно не в них.
PROBES: tuple[tuple[str, int], ...] = (
    ("1.1.1.1", 443),
    ("8.8.8.8", 443),
    ("9.9.9.9", 443),
)

#: Сколько ждать ответа. Это проверка «есть ли вообще связь», а не замер
#: скорости: живой канал отвечает за доли секунды, а на мёртвом эти
#: секунды множатся на число адресов.
TIMEOUT = 3.0


def reachable(host: str, port: int, timeout: float = TIMEOUT) -> bool:
    """Открывается ли соединение с этим адресом. Ничего не посылаем."""
    try:
        with socket.create_connection((host, int(port)), timeout=timeout):
            return True
    except OSError as exc:
        log.debug("Адрес %s:%s не отвечает: %s", host, port, exc)
        return False


def online(extra=()) -> bool:
    """Связь есть, если ответил хоть кто-то.

    `extra` — адреса, которые важны именно нам: прокси, через который
    сейчас идёт прогон. Он спрашивается первым и обычно отвечает сразу,
    так что до публичных адресов дело не доходит вовсе.
    """
    for host, port in tuple(extra) + PROBES:
        if host and reachable(str(host), int(port)):
            return True
    return False


def offline(extra=()) -> bool:
    """Связи нет ни через что. Обратное к `online`, для читаемости места
    вызова: `if offline(...)` — это условие, ради которого модуль и есть."""
    return not online(extra)
