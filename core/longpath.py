"""Длинные пути Windows.

Windows режет пути на 260 знаках. У книги с китайским названием и главами
вроде «Chapter 111: Thirty Years East of the River, Thirty Years West of
the River, Don't Bully the Poor Son of a Concubine» этот предел
переступается легко — а вместе с папкой корзины и подавно:

    C:\\Users\\...\\data\\backup\\2026-09-06_13-09-26_download\\0134 - ...txt

Ошибка при этом приходит обманчивая: «Системе не удается найти указанный
путь». Читается как «файла нет», хотя файл есть и лежит ровно там, где
сказано, — просто имя длиннее, чем разрешено спрашивать обычным способом.

Приставка `\\\\?\\` снимает предел: с ней путь уходит в ядро как есть,
минуя разбор старого образца. Требования к такому пути жёсткие — он
должен быть полным и с обратными косыми, — поэтому приводим его сами.

На всём, кроме Windows, ничего не делаем: там предела нет, а приставка
стала бы частью имени файла.
"""

from __future__ import annotations

import ntpath
import os

#: Приставка для обычных путей: `C:\...` → `\\?\C:\...`.
WIDE = "\\\\?\\"

#: Она же для сетевых: `\\сервер\шара` → `\\?\UNC\сервер\шара`. Просто
#: приписать `\\?\` к сетевому пути нельзя — получится имя, которого нет.
WIDE_UNC = "\\\\?\\UNC"


def windows() -> bool:
    """Та ли мы система. Отдельной строкой — её подменяют в проверках."""
    return os.name == "nt"


def wide(path) -> str:
    """Путь, которым можно открыть файл с длинным именем.

    Возвращает строку, а не `Path`: приставка `\\\\?\\` для `Path` —
    обычные части пути, и он их «упростит» обратно при первом же
    сравнении. Строку же принимают и `open`, и `shutil`.
    """
    text = str(path)
    if not windows() or text.startswith(WIDE):
        return text

    # Путь должен быть полным: приставка отключает разбор, а вместе с ним
    # и подстановку текущей папки.
    #
    # Через `ntpath`, а не `os.path`. Правила у длинного имени виндовые, а
    # `os.path` на другой системе — это `posixpath`: обратную косую он за
    # разделитель не считает вовсе, и `\\сервер\шара` превращается у него
    # в имя файла целиком. Проверки от этого показывали успех там, где на
    # самой Windows вышла бы неправда.
    try:
        full = ntpath.abspath(text)
    except (OSError, ValueError):
        return text

    if full.startswith("\\\\"):
        # Сетевой путь: `\\сервер\шара\...` → `\\?\UNC\сервер\шара\...`
        return WIDE_UNC + full[1:]
    return WIDE + full


def opened(path, mode: str = "r", **rest):
    """`open`, которому длинное имя не помеха."""
    return open(wide(path), mode, **rest)
