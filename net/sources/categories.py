def board_key(audience: str, kind: str) -> str:
    return f"{audience}_{kind}"


def path(audience: str, kind: str, category: str) -> str:
    """Адрес страницы рейтинга."""
    return f"/rank/{audience}_{kind}_{category}"


def translate(category_id: str, original: str = "") -> dict:
    """Название категории по-русски.

    Незнакомая категория показывается оригиналом и помечается: на сайте
    мог появиться новый жанр, и молча прятать его нельзя.
    """
    known = NAMES.get(str(category_id))
    return {
        "id": str(category_id),
        "original": original,
        "name": known or original or str(category_id),
        "translated": known is not None,
    }
