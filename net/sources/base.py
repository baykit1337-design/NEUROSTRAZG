"""Что обязан уметь источник и на каком языке он говорит с качалкой.

Внутреннее представление книги и главы взято из `mvl/api.py` — то самое,
на котором уже работают докачка, имена файлов и отчёты. Заводить второе
ради второго источника было бы ошибкой: разошлись бы они на первой же
правке.
"""

from __future__ import annotations

from mvl.api import Chapter, Novel, Toc


class SourceBroken(Exception):
    """Источник изменился и разобрать его больше нельзя.

    Отдельно от сетевых ошибок: «сайт не ответил» лечится повтором, а
    «структура ответа другая» — только правкой модуля. Смешивать их значит
    предлагать человеку жать «повторить» до бесконечности.
    """


class SourceUnreachable(Exception):
    """Сервер самого источника не ответил, и прокси тут ни при чём.

    Источник может ходить мимо пула — например, к стороннему серверу,
    которому прокси не нужен. Его молчание выглядело как отказ прокси:
    качалка перебирала весь список по три попытки на адрес, тратила на
    это минуты и заканчивала неправдой «рабочих прокси не осталось» —
    при том, что ни один из них даже не использовался.

    Менять адрес бессмысленно, повторять по каждой главе тоже: если
    сервер молчит, он молчит для всей книги. Такой отказ останавливает
    прогон сразу и называет виновника.
    """


class Source:
    """Интерфейс источника.

    Три метода. Всё остальное — папки, имена, прогресс, докачка, прокси —
    общее и живёт в качалке.
    """

    #: Ключ для настроек и запросов.
    key = ""
    #: Как называется на экране.
    name = ""
    #: Что писать в самом поле, серым. У источников оно разное: у одного
    #: слаг, у другого числовой код, и общий заполнитель сбивал бы с толку.
    placeholder = ""
    #: Пояснение под полем.
    hint = ""
    #: Нужен ли этому источнику прокси-пул.
    needs_proxy = False
    #: Флажок остановки прогона; качалка ставит его перед запуском.
    #: Нужен источнику, который ходит своим клиентом мимо качалки: без
    #: него «Остановить» ждёт всю лесенку повторов этого клиента.
    cancel = None
    #: Сроки ожидания, выставленные человеком; качалка ставит их туда же.
    #: Источнику со своим клиентом настройка с экрана иначе не доходит.
    timeouts: dict = {}

    def find(self, client, query: str) -> Novel:
        """Книга по ссылке, слагу или коду."""
        raise NotImplementedError

    def toc(self, client, novel: Novel, first: int = 1, last: int | None = None,
            on_progress=None) -> Toc:
        """Оглавление в заданном диапазоне."""
        raise NotImplementedError

    def chapter(self, client, chapter: Chapter) -> tuple[str, str]:
        """Заголовок и текст одной главы."""
        raise NotImplementedError

    def close(self) -> None:
        """Отпустить своё, если источник что-то завёл сам.

        Клиент к сайту заводит и закрывает качалка. Но источник может
        ходить и мимо него — например, к стороннему серверу, которому
        прокси витрины не нужен, — и тогда закрывать эту сессию больше
        некому. Большинству источников закрывать нечего.
        """

    def as_dict(self) -> dict:
        return {"key": self.key, "name": self.name, "hint": self.hint,
                "placeholder": self.placeholder or self.hint,
                "needs_proxy": self.needs_proxy}


__all__ = ["Chapter", "Novel", "Source", "SourceBroken", "SourceUnreachable",
           "Toc"]
