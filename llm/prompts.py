"""Все промпты в одном месте.

Главное правило: в промпте нет ни одного примера из конкретной книги.
Только описание схемы и перечень типов. Стоит подставить в пример
питомца — и модель начнёт искать питомцев там, где их нет, а найдя,
придумает.

По той же причине примеры значений даются обобщённо («имя», «роль»), а не
через выдуманного персонажа.
"""

from __future__ import annotations

from core.registry import LINK_TYPES, STATUS_ALIVE, STATUS_DEAD, TYPES

#: Схема ответа. Описываем словами и структурой, без наполнения.
FACTS_SCHEMA = """{
  "chapter": <номер главы, число>,
  "entities": [
    {
      "name": "<имя или название, как в тексте>",
      "type": "<один из типов ниже>",
      "status": "<жив | мёртв | неизвестно>",
      "attributes": {"<признак>": "<значение>"}
    }
  ],
  "links": [
    {"from": "<имя>", "to": "<имя>", "type": "<один из типов связей>"}
  ],
  "events": [
    {
      "type": "<что произошло: использование, встреча, гибель, получение>",
      "actor": "<кто действует>",
      "object": "<над чем или над кем>",
      "quote": "<точная цитата из главы, до 200 символов>"
    }
  ]
}"""


FACTS = """Ты разбираешь одну главу книги и возвращаешь факты из неё.

Верни СТРОГО JSON по схеме ниже. Без пояснений, без разметки, без текста
вокруг — только JSON.

Схема:
{schema}

Допустимые значения "type" у сущностей:
{types}

Допустимые значения "type" у связей:
{links}

Правила:
1. Записывай только то, что прямо сказано в тексте главы. Ничего не
   додумывай и не достраивай по жанровым ожиданиям.
2. Имена пиши ровно так, как они стоят в тексте, не приводя к
   единообразию и не переводя.
3. Если в главе нет сущностей какого-то вида — верни для них пустой
   список, а не выдуманные записи.
4. "quote" — дословный кусок главы, не пересказ. Не длиннее 200 символов.
5. "attributes" заполняй только теми признаками, которые названы в тексте
   (например пол, звание, принадлежность к группе). Пустой объект
   допустим и предпочтительнее выдумки.
6. Статус "{dead}" ставь, только если гибель описана в этой главе или
   прямо упомянута как случившаяся.

Номер главы: {number}
Название главы: {title}

Текст главы:
{text}"""


SUMMARY = """Ниже перечислены факты, собранные по главам книги.

Напиши по ним аннотацию книги на 1000–1500 символов: о чём она, кто
действует, что движет сюжетом. Пиши по-русски, сплошным текстом, без
списков и без заголовков. Не придумывай событий, которых в фактах нет.

Факты:
{facts}"""


def facts(number, title: str, text: str) -> str:
    """Промпт для разбора одной главы."""
    return FACTS.format(
        schema=FACTS_SCHEMA,
        types=" · ".join(TYPES),
        links=" · ".join(LINK_TYPES),
        dead=STATUS_DEAD,
        alive=STATUS_ALIVE,
        number=number if number is not None else "неизвестен",
        title=title or "без названия",
        text=text,
    )


def summary(lines) -> str:
    """Промпт для общей аннотации книги."""
    return SUMMARY.format(facts="\n".join(lines))
